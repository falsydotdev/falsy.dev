// Writes src/scene/lights-grid.ts, the coarse global city-lights grid shot planning reads (see
// src/scene/lights.ts): the mean light of each 1° cell of the mosaic step's 3 km lights raster.
//   node scripts/tiles/lights-grid.mjs      after earth-mosaic.mjs --coarse lights
import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { listRasters } from './mosaic-rasters.mjs';
import { lightOf } from '../../src/scene/tiles/lights-codec.ts';
import { LIGHTS_GRID_CELL_DEG, encodeLight } from '../../src/scene/lights.ts';

const r = listRasters('lights').find((x) => x.w === 13500 && x.h === 6750);
if (!r) throw new Error('No 3 km lights raster: run scripts/tiles/earth-mosaic.mjs --coarse lights first');
const grey = readFileSync(r.file);
const cols = 360 / LIGHTS_GRID_CELL_DEG;
const rows = 180 / LIGHTS_GRID_CELL_DEG;
const per = r.w / cols;
const sum = new Float64Array(cols * rows);
for (let y = 0; y < r.h; y++) {
  const row = Math.floor(y / per) * cols;
  for (let x = 0; x < r.w; x++) sum[row + Math.floor(x / per)] += lightOf(grey[y * r.w + x]);
}
const values = Uint8Array.from(sum, (s) => encodeLight(s / (per * per)));
const out = new URL('../../src/scene/lights-grid.ts', import.meta.url);
await writeFile(
  out,
  `// Generated by scripts/tiles/lights-grid.mjs from NASA Black Marble 2016 (3 km grey). Don't edit.\n` +
    `// ${cols}×${rows} bytes, row 0 at 90°N and column 0 at 180°W, base64; decode with src/scene/lights.ts.\n` +
    `export const LIGHTS_GRID_BASE64 =\n  '${Buffer.from(values).toString('base64')}';\n`,
);
console.log(`${out.pathname}: ${values.filter(Boolean).length} lit cells of ${values.length}`);
