// Writes src/scene/zones.ts, the timezone-to-coordinates table the home pass reads (see
// src/scene/timezone.ts), from IANA tzdb's zone.tab and backward files (both public domain).
//   node scripts/zones.mjs <dir holding zone.tab, backward, and version>
// zone.tab, not zone1970.tab: zone1970.tab merges countries, so Stockholm would get Berlin's coordinates.
import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Usage: node scripts/zones.mjs <tzdata dir>');
const read = (name) => readFileSync(join(dir, name), 'utf8');

const NAME = /^[A-Za-z][A-Za-z0-9_+-]*(\/[A-Za-z0-9_+-]+)*$/;
// Abbreviation links name a clock, not a place: EST links to America/Panama.
const NOT_PLACES = new Set(['CET', 'EET', 'MET', 'WET', 'EST', 'MST', 'HST']);

const version = read('version').trim();
if (!/^\d{4}[a-z]$/.test(version)) throw new Error(`Unexpected tzdb version ${JSON.stringify(version)}`);

// ISO 6709 ±DDMM±DDDMM or ±DDMMSS±DDDMMSS, to tenths of a degree.
function tenths(sign, deg, min, sec = '0') {
  const value = Number(deg) + Number(min) / 60 + Number(sec) / 3600;
  return Math.round((sign === '-' ? -value : value) * 10);
}

const zones = new Map();
for (const line of read('zone.tab').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coords, name] = line.split('\t');
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(coords ?? '');
  if (!m || !NAME.test(name ?? '')) throw new Error(`Unexpected zone.tab line: ${JSON.stringify(line)}`);
  const lat = tenths(m[1], m[2], m[3], m[4]);
  const lon = tenths(m[5], m[6], m[7], m[8]);
  if (Math.abs(lat) > 900 || Math.abs(lon) > 1800) throw new Error(`Coordinates out of range: ${JSON.stringify(line)}`);
  zones.set(name, [lat, lon]);
}

const aliases = new Map();
for (const line of read('backward').split('\n')) {
  const m = /^Link\s+(\S+)\s+(\S+)/.exec(line);
  if (!m) continue;
  const [, target, name] = m;
  if (!NAME.test(target) || !NAME.test(name)) throw new Error(`Unexpected backward line: ${JSON.stringify(line)}`);
  // Links to UTC and GMT have no place, and a name zone.tab lists keeps its own city.
  if (zones.has(name) || !zones.has(target) || NOT_PLACES.has(name)) continue;
  aliases.set(name, target);
}

const sorted = (map) => [...map].sort(([a], [b]) => (a < b ? -1 : 1));
const out = new URL('../src/scene/zones.ts', import.meta.url);
await writeFile(
  out,
  `// Generated by scripts/zones.mjs from IANA tzdb ${version} zone.tab and backward (public domain). Don't edit.\n` +
    `// Each line: zone name, then its principal city's latitude and longitude (east) in tenths of a degree.\n` +
    `export const ZONES = \`${sorted(zones).map(([n, [lat, lon]]) => `${n} ${lat} ${lon}`).join('\n')}\`;\n` +
    `// Each line: a legacy name browsers still report, then the zone it links to.\n` +
    `export const ZONE_ALIASES = \`${sorted(aliases).map(([n, t]) => `${n} ${t}`).join('\n')}\`;\n`,
);
console.log(`${out.pathname}: ${zones.size} zones, ${aliases.size} aliases (tzdb ${version})`);
